/* ==========================================================================
 * 01-params.js —— S0 系统阈值参数集
 *
 * @层          数据模型层（core）
 * @技术特征
 *   【特征 S0-1】系统阈值参数集 P：全部判定阈值集中定义、独立于算法实现，
 *                支持按不同仓储类型（1.3 级工库房 / 中转库 / 零售库）整组替换而不改动算法代码。
 *   【特征 S0-2】五阶段功能时间线 TL：把「数据获取（S1、S2）→ 特征构造（S3）→
 *                风险判定（S4）→ 校验预警（S5）」划分为时间上首尾相接的 5 个阶段，
 *                使同一条数据流可被复用为 5 个相互印证的判断依据。
 *   【特征 S4-3】账面造假考察窗口 BOOK_WIN。
 * @说明
 *   本模块只做「参数声明」，不含任何计算逻辑，是全部算法的数值边界来源。
 * ========================================================================== */
(function (NS) {
  'use strict';

  /**
   * 【特征 S0-1】系统阈值参数集。
   * 所有字段均可在不修改算法代码的前提下整组替换。
   */
  var P = {
    /** 目标仓储设计容量 C（吨）。饱和度分母。 */
    capacity: 800,
    /** 满载阈值：S(t) ≥ fullRatio 视为达到满载状态。 */
    fullRatio: 0.85,
    /** 静止阈值（km/h）：瞬时移动速度低于该值视为「静止」。 */
    staticSpeed: 2,
    /** 装卸容忍时间阈值（min）：正常装卸作业的最长合理耗时，超过即视为「滞留」。 */
    tolerance: 15,
    /** 滞留报警阈值：异常滞留指数 I(t) ≥ stayThreshold 视为滞留异常。 */
    stayThreshold: 0.60,
    /** 风险置信度阈值：多源数据一致性校验通过线（0~1，与百分制比较时乘 100）。 */
    confThreshold: 0.85,
    /** 地理电子围栏半径（度，约 800 m）。以目标仓储坐标为圆心。 */
    fenceR: 0.0082,
    /** 账面造假：预设时间段内饱和度下降阈值（15%）。 */
    bookDrop: 0.15,
    /** T+0 时刻的初始库存（吨）。 */
    stock0: 498
  };

  /**
   * 【特征 S0-2】五阶段功能时间线（单位：分钟，相对监测起始时刻 T+0）。
   * s1..s5 为各阶段起止，end 为整条时间线的循环终点。
   */
  var TL = { s1: [0, 9], s2: [9, 17], s3: [17, 32], s4: [32, 41], s5: [41, 56], end: 60 };

  /**
   * 【特征 S4-3】账面造假风险的考察窗口起点（分钟）。
   * 只有在该时刻之后才开始驶离的车辆，才计入「驶离轨迹」，
   * 从而把「正常装卸后离场」与「风险窗口内的离场」区分开。
   */
  var BOOK_WIN = 36.8;

  NS.__declare('01-params', ['P', 'TL', 'BOOK_WIN']);
  NS.P = P;
  NS.TL = TL;
  NS.BOOK_WIN = BOOK_WIN;
})(window.FWCore);
